#!/usr/bin/env python3
"""Generate shared Rust/TypeScript contract identities; use --check in CI."""

from __future__ import annotations

import argparse
from pathlib import Path

from result_contract import ROOT, contract_values


def generated_files(root: Path = ROOT) -> dict[Path, str]:
    value = contract_values(root)["RESULT_CONTRACT_SHA256"]
    header = "// Generated by scripts/generate_result_contract.py; do not edit.\n"
    return {
        root / "src/result_contract.rs": (
            header + f'pub const RESULT_CONTRACT_SHA256: &str =\n    "{value}";\n'
        ),
        root / "dashboard/src/lib/result-contract.generated.ts": (
            header + f"export const RESULT_CONTRACT_SHA256 =\n  '{value}'\n"
        ),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for path, expected in generated_files().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected, encoding="utf-8")
    if stale:
        print("Stale result contract files: " + ", ".join(stale))
        print("Run python3 scripts/generate_result_contract.py after exporting schemas.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
