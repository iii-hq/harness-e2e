#!/usr/bin/env python3
"""Generate shared Rust/TypeScript contract identities; use --check in CI."""

from __future__ import annotations

import argparse
from pathlib import Path

from result_contract import ROOT, contract_values


def generated_files(root: Path = ROOT) -> dict[Path, str]:
    values = contract_values(root)
    header = "// Generated by scripts/generate_result_contract.py; do not edit.\n"
    rust = header
    typescript = header
    for name, value in values.items():
        if isinstance(value, int):
            rust += f"pub const {name}: u32 = {value};\n"
            typescript += f"export const {name} = {value}\n"
        else:
            rust += f'pub const {name}: &str =\n    "{value}";\n'
            typescript += f"export const {name} =\n  '{value}'\n"
    return {
        root / "src/result_contract.rs": rust,
        root / "dashboard/src/lib/result-contract.generated.ts": typescript,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for path, expected in generated_files().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected, encoding="utf-8")
    if stale:
        print("Stale result contract files: " + ", ".join(stale))
        print("Run python3 scripts/generate_result_contract.py after exporting schemas.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
